package com.fongmi.android.tv.ui.theme

import androidx.compose.ui.unit.dp

/**
 * JetStream Spacing System
 * 统一的间距系统，遵循 8dp 网格原则
 */
object JetStreamSpacing {
    // Base spacing unit
    val Base = 8.dp

    // Extra Small spacing
    val ExtraSmall = 4.dp

    // Small spacing
    val Small = 8.dp

    // Medium spacing
    val Medium = 12.dp

    // Large spacing
    val Large = 16.dp

    // Extra Large spacing
    val ExtraLarge = 24.dp

    // Extra Extra Large spacing
    val ExtraExtraLarge = 32.dp

    // Huge spacing
    val Huge = 48.dp

    // Component specific spacing
    val CardPadding = 22.dp
    val CardPaddingLarge = 28.dp
    val ChipHorizontalPadding = 14.dp
    val ChipVerticalPadding = 8.dp
    val ButtonHorizontalPadding = 18.dp
    val ButtonVerticalPadding = 12.dp
    val IconPadding = 10.dp
}

/**
 * JetStream Size System
 * 统一的尺寸系统
 */
object JetStreamSizes {
    // Icon sizes
    val IconExtraSmall = 16.dp
    val IconSmall = 20.dp
    val IconMedium = 24.dp
    val IconLarge = 32.dp
    val IconExtraLarge = 48.dp

    // Button sizes
    val ButtonSmall = 32.dp
    val ButtonMedium = 40.dp
    val ButtonLarge = 48.dp

    // Chip sizes
    val ChipSmall = 28.dp
    val ChipMedium = 36.dp
    val ChipLarge = 44.dp

    // Card sizes
    val CardMinHeight = 64.dp
    val CardHeaderHeight = 48.dp

    // Avatar sizes
    val AvatarSmall = 32.dp
    val AvatarMedium = 40.dp
    val AvatarLarge = 56.dp
}

/**
 * JetStream Border System
 * 统一的边框系统
 */
object JetStreamBorders {
    val Thin = 1.dp
    val Medium = 1.5.dp
    val Thick = 2.dp
}
